"""# Funzione generatrice"""

def generate_synthetic_nuclei_image(min_num_nuclei=346,
                                    max_num_nuclei=1028,
                                    mean_nuclei=18.18,
                                    sd_nuclei=4.22,
                                    num_clusters=20,
                                    max_length=200, min_length=75,
                                    cluster_strength=0.4,
                                    cluster_width=2.5,
                                    blur_radius=1.3,
                                    min_intensity=100, max_intensity=255,
                                    cluster_intensity_boost=70,
                                    elliptical_cluster_ratio=0.40,
                                    elliptical_cluster_min_radius=15, elliptical_cluster_max_radius=20,
                                    background_mean=15,
                                    background_std=8,
                                    background_max=50,
                                    min_distance=0,
                                    max_attempts=50,
                                    dimensione_box=1.25,
                                    texture_strength=0.25,
                                    overlap_darkening=0.25,
                                    output_path=None):

    width = 1388
    height = 1040

    background = np.random.normal(background_mean, background_std, (height, width))
    background = np.clip(background, 0, background_max).astype(np.float32)

    nuclei_layer = np.zeros((height, width), dtype=np.float32)

    annotations = []
    placed_nuclei = []
    placed_arr = None  # array numpy per il collision check vettorizzato

    num_clusters = max(int(np.random.normal(num_clusters, num_clusters/10)), 0)
    num_elliptical_clusters = int(num_clusters * max(np.random.normal(elliptical_cluster_ratio, elliptical_cluster_ratio/5), 0))
    num_line_clusters = num_clusters - num_elliptical_clusters

    cluster_lines = []
    for _ in range(num_line_clusters):
        x1 = np.random.randint(mean_nuclei * 2, width - mean_nuclei * 2)
        y1 = np.random.randint(mean_nuclei * 2, height - mean_nuclei * 2)
        line_length = np.random.uniform(min_length, max_length)
        angle = np.random.uniform(0, 2 * np.pi)
        x2 = x1 + line_length * np.cos(angle)
        y2 = y1 + line_length * np.sin(angle)
        cluster_lines.append(('line', ((x1, y1), (x2, y2))))

    elliptical_clusters = []
    for _ in range(num_elliptical_clusters):
        center_x = np.random.randint(mean_nuclei * 2, width - mean_nuclei * 2)
        center_y = np.random.randint(mean_nuclei * 2, height - mean_nuclei * 2)
        radius_x = np.random.uniform(elliptical_cluster_min_radius, elliptical_cluster_max_radius)
        radius_y = np.random.uniform(radius_x * 0.8, radius_x * 1.2)
        elliptical_clusters.append(('ellipse', (center_x, center_y, radius_x, radius_y)))

    all_clusters = cluster_lines + elliptical_clusters

    target_nuclei = int(np.random.uniform(min_num_nuclei, max_num_nuclei))

    for _ in range(target_nuclei):
        for attempt in range(max_attempts):
            is_in_cluster = False

            if np.random.random() < cluster_strength and all_clusters:
                is_in_cluster = True
                cluster_type, cluster_data = all_clusters[np.random.randint(0, len(all_clusters))]

                if cluster_type == 'line':
                    (x1, y1), (x2, y2) = cluster_data
                    t = np.random.random()
                    line_x = x1 + t * (x2 - x1)
                    line_y = y1 + t * (y2 - y1)
                    perpendicular_angle = np.arctan2(y2 - y1, x2 - x1) + np.pi / 2
                    perpendicular_distance = np.random.normal(0, cluster_width)
                    center_x = int(np.clip(line_x + perpendicular_distance * np.cos(perpendicular_angle),
                                           mean_nuclei, width - mean_nuclei))
                    center_y = int(np.clip(line_y + perpendicular_distance * np.sin(perpendicular_angle),
                                           mean_nuclei, height - mean_nuclei))
                else:
                    center_cluster_x, center_cluster_y, radius_x, radius_y = cluster_data
                    ellipse_attempts = 0
                    found = False
                    while ellipse_attempts < 100:
                        rand_x = np.random.uniform(-radius_x, radius_x)
                        rand_y = np.random.uniform(-radius_y, radius_y)
                        if (rand_x / radius_x) ** 2 + (rand_y / radius_y) ** 2 <= 1:
                            center_x = int(center_cluster_x + rand_x)
                            center_y = int(center_cluster_y + rand_y)
                            if (mean_nuclei <= center_x <= width - mean_nuclei and
                                mean_nuclei <= center_y <= height - mean_nuclei):
                                found = True
                                break
                        ellipse_attempts += 1
                    if not found:
                        continue
            else:
                center_x = np.random.randint(0, width)
                center_y = np.random.randint(0, height)

            semi_major = np.random.normal(mean_nuclei, sd_nuclei)
            semi_minor = np.random.normal(mean_nuclei, sd_nuclei)

            # --- Collision check VETTORIZZATO ---
            max_radius = max(semi_major, semi_minor)
            collision = False
            if placed_arr is not None and len(placed_arr) > 0:
                dx = placed_arr[:, 0] - center_x
                dy = placed_arr[:, 1] - center_y
                distances = np.sqrt(dx**2 + dy**2)
                min_allowed = max_radius + placed_arr[:, 2] + min_distance
                collision = np.any(distances < min_allowed)

            if collision:
                continue

            angle = np.random.uniform(0, 2 * np.pi)
            base_intensity = int(np.random.uniform(min_intensity, max_intensity))
            intensity = min(255, base_intensity + cluster_intensity_boost) if is_in_cluster else base_intensity

            points = []
            for t in np.linspace(0, 2 * np.pi, 50):
                x = semi_major * np.cos(t)
                y = semi_minor * np.sin(t)
                x_rot = x * np.cos(angle) - y * np.sin(angle)
                y_rot = x * np.sin(angle) + y * np.cos(angle)
                points.append((center_x + x_rot, center_y + y_rot))

            # --- Disegna SOLO su una patch piccola, non sull'immagine intera ---
            margin = int(max_radius) + 3
            patch_size = margin * 2
            local_points = [(px - center_x + margin, py - center_y + margin) for px, py in points]

            patch_img = Image.new('L', (patch_size, patch_size), 0)
            patch_draw = ImageDraw.Draw(patch_img)
            patch_draw.polygon(local_points, fill=intensity)
            patch_array = np.array(patch_img, dtype=np.float32)

            if texture_strength > 0:
                noise = np.random.normal(0, intensity * texture_strength, patch_array.shape).astype(np.float32)
                patch_array = np.where(patch_array > 0, np.clip(patch_array + noise, 0, 255), patch_array)

            # Calcola la regione corrispondente in nuclei_layer, con clipping ai bordi immagine
            y0, y1_ = center_y - margin, center_y + margin
            x0, x1_ = center_x - margin, center_x + margin
            y0c, y1c = max(0, y0), min(height, y1_)
            x0c, x1c = max(0, x0), min(width, x1_)
            py0, py1 = y0c - y0, patch_size - (y1_ - y1c)
            px0, px1 = x0c - x0, patch_size - (x1_ - x1c)

            region = nuclei_layer[y0c:y1c, x0c:x1c]
            patch_crop = patch_array[py0:py1, px0:px1]

            overlap_mask = (region > 0) & (patch_crop > 0)
            merged = np.maximum(region, patch_crop)
            if overlap_darkening > 0:
                merged[overlap_mask] *= (1 - overlap_darkening)

            nuclei_layer[y0c:y1c, x0c:x1c] = merged

            # Aggiorna placed_nuclei e l'array numpy per il prossimo collision check
            placed_nuclei.append((center_x, center_y, max_radius))
            placed_arr = np.array(placed_nuclei)

            points_array = np.array(points)
            min_x, max_x = np.min(points_array[:, 0]), np.max(points_array[:, 0])
            min_y, max_y = np.min(points_array[:, 1]), np.max(points_array[:, 1])

            bbox_center_x = (min_x + max_x) / 2
            bbox_center_y = (min_y + max_y) / 2
            bbox_width = (max_x - min_x) * dimensione_box
            bbox_height = (max_y - min_y) * dimensione_box

            norm_center_x = bbox_center_x / width
            norm_center_y = bbox_center_y / height
            norm_width = bbox_width / width
            norm_height = bbox_height / height

            annotations.append(f"0 {norm_center_x:.6f} {norm_center_y:.6f} {norm_width:.6f} {norm_height:.6f}")

            break

    final_image = background + nuclei_layer
    final_image = np.clip(final_image, 0, 255).astype(np.uint8)

    img = Image.fromarray(final_image)  # niente mode='L'

    if blur_radius > 0:
        img = img.filter(ImageFilter.GaussianBlur(radius=max(np.random.normal(blur_radius, blur_radius/50), 0)))

    if output_path:
        img.save(output_path)
        txt_path = output_path.rsplit('.', 1)[0] + '.txt'
        with open(txt_path, 'w') as f:
            f.write('\n'.join(annotations))

    return img, annotations


def sample_truncated_normal(mean, sd, min_val=None, max_tries=50):
    """Campiona da una normale, ricampionando se sotto la soglia minima."""
    for _ in range(max_tries):
        val = np.random.normal(mean, sd)
        if min_val is None or val >= min_val:
            return val
    return max(np.random.normal(mean, sd), min_val if min_val is not None else 0)


def generate_synthetic_zoom_nuclei_image(
                                    crop_width_mean=77.50629, crop_width_sd=31.28389,
                                    crop_height_mean=75.78322, crop_height_sd=29.68342,
                                    crop_min_size=20,

                                    n_nuclei_mean=17.38741, n_nuclei_sd=9.509518,

                                    nucleus_size_mean=15.61835, nucleus_size_sd=3.133576,

                                    num_clusters=None,
                                    max_length=200, min_length=75,
                                    cluster_strength=0.95,
                                    cluster_width=2.5,
                                    blur_radius=1.3,
                                    min_intensity=100, max_intensity=255,
                                    cluster_intensity_boost=70,
                                    elliptical_cluster_ratio=0.75,
                                    elliptical_cluster_min_radius=15,
                                    elliptical_cluster_max_radius=25,
                                    background_mean=15,
                                    background_std=20,
                                    background_max=50,
                                    min_distance=-5.5,
                                    max_attempts=50,
                                    dimensione_box=1.3,
                                    texture_strength=0.25,
                                    overlap_darkening=0.1,
                                    output_path=None):

    width = int(sample_truncated_normal(crop_width_mean, crop_width_sd, min_val=crop_min_size))
    height = int(sample_truncated_normal(crop_height_mean, crop_height_sd, min_val=crop_min_size))

    target_nuclei = max(2, int(sample_truncated_normal(n_nuclei_mean, n_nuclei_sd, min_val=3)))

    mean_nuclei = nucleus_size_mean / 2 / dimensione_box
    sd_nuclei = nucleus_size_sd / 2 / dimensione_box

    if num_clusters is None:
        num_clusters = random.choice([1, 2])

    background = np.random.normal(background_mean, background_std, (height, width))
    background = np.clip(background, 0, background_max).astype(np.float32)

    nuclei_layer = np.zeros((height, width), dtype=np.float32)
    annotations = []
    placed_nuclei = []

    num_elliptical_clusters = int(num_clusters * max(np.random.normal(elliptical_cluster_ratio, elliptical_cluster_ratio/5), 0))
    num_line_clusters = num_clusters - num_elliptical_clusters

    margin = max(int(mean_nuclei * 1.5), 2)
    margin = min(margin, min(width, height) // 3) if min(width, height) > 6 else 1

    cluster_lines = []
    for _ in range(num_line_clusters):
        x1 = np.random.randint(margin, max(margin + 1, width - margin))
        y1 = np.random.randint(margin, max(margin + 1, height - margin))
        line_length = np.random.uniform(min(min_length, width/2), min(max_length, max(width, height)))
        angle = np.random.uniform(0, 2 * np.pi)
        x2 = x1 + line_length * np.cos(angle)
        y2 = y1 + line_length * np.sin(angle)
        cluster_lines.append(('line', ((x1, y1), (x2, y2))))

    elliptical_clusters = []
    for _ in range(num_elliptical_clusters):
        center_x = np.random.randint(margin, max(margin + 1, width - margin))
        center_y = np.random.randint(margin, max(margin + 1, height - margin))
        radius_x = np.random.uniform(elliptical_cluster_min_radius, min(elliptical_cluster_max_radius, width/2))
        radius_y = np.random.uniform(radius_x * 0.8, radius_x * 1.2)
        elliptical_clusters.append(('ellipse', (center_x, center_y, radius_x, radius_y)))

    all_clusters = cluster_lines + elliptical_clusters

    for _ in range(target_nuclei):
        for attempt in range(max_attempts):
            is_in_cluster = False

            if np.random.random() < cluster_strength and all_clusters:
                is_in_cluster = True
                cluster_type, cluster_data = all_clusters[np.random.randint(0, len(all_clusters))]

                if cluster_type == 'line':
                    (x1, y1), (x2, y2) = cluster_data
                    t = np.random.random()
                    line_x = x1 + t * (x2 - x1)
                    line_y = y1 + t * (y2 - y1)
                    perpendicular_angle = np.arctan2(y2 - y1, x2 - x1) + np.pi / 2
                    perpendicular_distance = np.random.normal(0, cluster_width)
                    center_x = int(np.clip(line_x + perpendicular_distance * np.cos(perpendicular_angle), 0, width - 1))
                    center_y = int(np.clip(line_y + perpendicular_distance * np.sin(perpendicular_angle), 0, height - 1))
                else:
                    center_cluster_x, center_cluster_y, radius_x, radius_y = cluster_data
                    ellipse_attempts = 0
                    found = False
                    while ellipse_attempts < 100:
                        rand_x = np.random.uniform(-radius_x, radius_x)
                        rand_y = np.random.uniform(-radius_y, radius_y)
                        if (rand_x / radius_x) ** 2 + (rand_y / radius_y) ** 2 <= 1:
                            center_x = int(center_cluster_x + rand_x)
                            center_y = int(center_cluster_y + rand_y)
                            if 0 <= center_x < width and 0 <= center_y < height:
                                found = True
                                break
                        ellipse_attempts += 1
                    if not found:
                        continue
            else:
                center_x = np.random.randint(0, width)
                center_y = np.random.randint(0, height)

            semi_major = max(np.random.normal(mean_nuclei, sd_nuclei), 2)
            semi_minor = max(np.random.normal(mean_nuclei, sd_nuclei), 2)

            collision = False
            max_radius = max(semi_major, semi_minor)
            for prev_center_x, prev_center_y, prev_radius in placed_nuclei:
                distance = np.sqrt((center_x - prev_center_x)**2 + (center_y - prev_center_y)**2)
                if distance < max_radius + prev_radius + min_distance:
                    collision = True
                    break
            if collision:
                continue

            angle = np.random.uniform(0, 2 * np.pi)
            base_intensity = int(np.random.uniform(min_intensity, max_intensity))
            intensity = min(255, base_intensity + cluster_intensity_boost) if is_in_cluster else base_intensity

            points = []
            for t in np.linspace(0, 2 * np.pi, 50):
                x = semi_major * np.cos(t)
                y = semi_minor * np.sin(t)
                x_rot = x * np.cos(angle) - y * np.sin(angle)
                y_rot = x * np.sin(angle) + y * np.cos(angle)
                points.append((center_x + x_rot, center_y + y_rot))

            temp_img = Image.new('L', (width, height), 0)
            temp_draw = ImageDraw.Draw(temp_img)
            temp_draw.polygon(points, fill=intensity)
            temp_array = np.array(temp_img, dtype=np.float32)

            if texture_strength > 0:
                noise = np.random.normal(0, intensity * texture_strength, temp_array.shape).astype(np.float32)
                temp_array = np.where(temp_array > 0, np.clip(temp_array + noise, 0, 255), temp_array)

            overlap_mask = (nuclei_layer > 0) & (temp_array > 0)
            nuclei_layer = np.maximum(nuclei_layer, temp_array)
            if overlap_darkening > 0:
                nuclei_layer[overlap_mask] *= (1 - overlap_darkening)

            placed_nuclei.append((center_x, center_y, max_radius))

            points_array = np.array(points)
            min_x, max_x = np.min(points_array[:, 0]), np.max(points_array[:, 0])
            min_y, max_y = np.min(points_array[:, 1]), np.max(points_array[:, 1])

            bbox_center_x = (min_x + max_x) / 2
            bbox_center_y = (min_y + max_y) / 2
            bbox_width = (max_x - min_x) * dimensione_box
            bbox_height = (max_y - min_y) * dimensione_box

            annotations.append(
                f"0 {bbox_center_x/width:.6f} {bbox_center_y/height:.6f} "
                f"{bbox_width/width:.6f} {bbox_height/height:.6f}"
            )
            break

    final_image = background + nuclei_layer
    final_image = np.clip(final_image, 0, 255).astype(np.uint8)
    img = Image.fromarray(final_image)  # niente mode='L', dedotto automaticamente

    if blur_radius > 0:
        img = img.filter(ImageFilter.GaussianBlur(radius=max(np.random.normal(blur_radius, blur_radius/15), 0)))

    if output_path:
        img.save(output_path)
        txt_path = output_path.rsplit('.', 1)[0] + '.txt'
        with open(txt_path, 'w') as f:
            f.write('\n'.join(annotations))

    return img, annotations


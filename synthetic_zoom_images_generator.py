import numpy as np
from PIL import Image, ImageDraw, ImageFilter
import random


def sample_truncated_normal(mean, sd, min_val=None, max_tries=50):
    for _ in range(max_tries):
        val = np.random.normal(mean, sd)
        if min_val is None or val >= min_val:
            return val
    return max(np.random.normal(mean, sd), min_val if min_val is not None else 0)


def generate_synthetic_zoom_hard_case(
                                # Dimensioni del crop
                                crop_width_mean=160, crop_width_sd=15,
                                crop_height_mean=160, crop_height_sd=15,
                                crop_min_size=80,

                                # Geometria del blob centrale (ellisse quasi circolare)
                                blob_radius_mean=30, blob_radius_sd=6,
                                blob_ellipticity_range=(0.85, 1.15),
                                blob_center_jitter=0.12,

                                # Densità nuclei DENTRO il blob
                                n_nuclei_mean=90, n_nuclei_sd=6,

                                # Nuclei sparsi FUORI dal blob (nuovo)
                                n_background_nuclei_mean=8, n_background_nuclei_sd=4,
                                background_min_distance=1,      # quasi nessun overlap tra i nuclei sparsi
                                background_max_attempts=50,

                                # Dimensione nucleo (calibrata sui dati reali — non toccare)
                                nucleus_size_mean=15.61835, nucleus_size_sd=3.133576,

                                # Overlap fortissimo (solo dentro il blob)
                                min_distance=-50,
                                max_attempts=150,

                                # Aspetto visivo del blob: massima uniformità, minima distinzione
                                min_intensity=200, max_intensity=255,
                                cluster_intensity_boost=40,
                                overlap_darkening=0.03,
                                texture_strength=0.10,

                                # Aspetto visivo dei nuclei sparsi (più "normale", non saturo)
                                background_min_intensity=100,
                                background_max_intensity=220,

                                background_mean=15,
                                background_std=20,
                                background_max=50,
                                blur_radius=1.5,
                                dimensione_box=1.3,

                                output_path=None):
    """
    Genera un crop sintetico 'caso difficile': un blob ellittico centrale
    densissimo di nuclei fortemente sovrapposti (macchia bianca), circondato
    da alcuni nuclei sparsi isolati sullo sfondo, più realistici.
    """

    width  = int(sample_truncated_normal(crop_width_mean, crop_width_sd, min_val=crop_min_size))
    height = int(sample_truncated_normal(crop_height_mean, crop_height_sd, min_val=crop_min_size))

    mean_nuclei = nucleus_size_mean / 2 / dimensione_box
    sd_nuclei = nucleus_size_sd / 2 / dimensione_box

    background = np.random.normal(background_mean, background_std, (height, width))
    background = np.clip(background, 0, background_max).astype(np.float32)

    nuclei_layer = np.zeros((height, width), dtype=np.float32)
    annotations = []
    placed_nuclei = []

    def draw_nucleus(center_x, center_y, semi_major, semi_minor, intensity):
        """Disegna un nucleo e aggiorna nuclei_layer + annotations. Riusata per blob e sparsi."""
        angle = np.random.uniform(0, 2 * np.pi)
        points = []
        for t in np.linspace(0, 2 * np.pi, 50):
            x = semi_major * np.cos(t)
            y = semi_minor * np.sin(t)
            x_rot = x * np.cos(angle) - y * np.sin(angle)
            y_rot = x * np.sin(angle) + y * np.cos(angle)
            points.append((center_x + x_rot, center_y + y_rot))

        temp_img = Image.new('L', (width, height), 0)
        temp_draw = ImageDraw.Draw(temp_img)
        temp_draw.polygon(points, fill=intensity)
        temp_array = np.array(temp_img, dtype=np.float32)

        if texture_strength > 0:
            noise = np.random.normal(0, intensity * texture_strength, temp_array.shape).astype(np.float32)
            temp_array = np.where(temp_array > 0, np.clip(temp_array + noise, 0, 255), temp_array)

        overlap_mask = (nuclei_layer > 0) & (temp_array > 0)
        nonlocal_layer = np.maximum(nuclei_layer, temp_array)
        if overlap_darkening > 0:
            nonlocal_layer[overlap_mask] *= (1 - overlap_darkening)

        points_array = np.array(points)
        min_x, max_x = np.min(points_array[:, 0]), np.max(points_array[:, 0])
        min_y, max_y = np.min(points_array[:, 1]), np.max(points_array[:, 1])
        bbox_center_x = (min_x + max_x) / 2
        bbox_center_y = (min_y + max_y) / 2
        bbox_width = (max_x - min_x) * dimensione_box
        bbox_height = (max_y - min_y) * dimensione_box

        annotations.append(
            f"0 {bbox_center_x/width:.6f} {bbox_center_y/height:.6f} "
            f"{bbox_width/width:.6f} {bbox_height/height:.6f}"
        )
        return nonlocal_layer

    # ================================================================
    # STEP 1 — Blob centrale densissimo
    # ================================================================

    jitter_x = int(width * blob_center_jitter)
    jitter_y = int(height * blob_center_jitter)
    blob_center_x = width // 2 + np.random.randint(-jitter_x, jitter_x + 1)
    blob_center_y = height // 2 + np.random.randint(-jitter_y, jitter_y + 1)

    blob_radius_x = max(sample_truncated_normal(blob_radius_mean, blob_radius_sd, min_val=10), 10)
    blob_radius_y = blob_radius_x * np.random.uniform(*blob_ellipticity_range)

    blob_radius_x = min(blob_radius_x, width / 2 - 2)
    blob_radius_y = min(blob_radius_y, height / 2 - 2)

    target_nuclei = max(5, int(sample_truncated_normal(n_nuclei_mean, n_nuclei_sd, min_val=10)))

    def sample_point_in_blob():
        for _ in range(200):
            rand_x = np.random.uniform(-blob_radius_x, blob_radius_x)
            rand_y = np.random.uniform(-blob_radius_y, blob_radius_y)
            if (rand_x / blob_radius_x) ** 2 + (rand_y / blob_radius_y) ** 2 <= 1:
                px = int(np.clip(blob_center_x + rand_x, 0, width - 1))
                py = int(np.clip(blob_center_y + rand_y, 0, height - 1))
                return px, py
        return None

    for _ in range(target_nuclei):
        for attempt in range(max_attempts):
            point = sample_point_in_blob()
            if point is None:
                continue
            center_x, center_y = point

            semi_major = max(np.random.normal(mean_nuclei, sd_nuclei), 2)
            semi_minor = max(np.random.normal(mean_nuclei, sd_nuclei), 2)
            max_radius = max(semi_major, semi_minor)

            collision = any(
                np.sqrt((center_x - px)**2 + (center_y - py)**2) < max_radius + pr + min_distance
                for px, py, pr in placed_nuclei
            )
            if collision:
                continue

            base_intensity = int(np.random.uniform(min_intensity, max_intensity))
            intensity = min(255, base_intensity + cluster_intensity_boost)

            nuclei_layer = draw_nucleus(center_x, center_y, semi_major, semi_minor, intensity)
            placed_nuclei.append((center_x, center_y, max_radius))
            break

    # ================================================================
    # STEP 2 — Nuclei sparsi sullo sfondo (NUOVO)
    # ================================================================

    n_background = max(0, int(sample_truncated_normal(n_background_nuclei_mean, n_background_nuclei_sd, min_val=0)))

    for _ in range(n_background):
        for attempt in range(background_max_attempts):
            center_x = np.random.randint(0, width)
            center_y = np.random.randint(0, height)

            semi_major = max(np.random.normal(mean_nuclei, sd_nuclei), 2)
            semi_minor = max(np.random.normal(mean_nuclei, sd_nuclei), 2)
            max_radius = max(semi_major, semi_minor)

            # collisione controllata contro TUTTI i nuclei già piazzati (blob incluso)
            # con una soglia molto meno permissiva: qui l'overlap deve essere raro
            collision = any(
                np.sqrt((center_x - px)**2 + (center_y - py)**2) < max_radius + pr + background_min_distance
                for px, py, pr in placed_nuclei
            )
            if collision:
                continue

            intensity = int(np.random.uniform(background_min_intensity, background_max_intensity))

            nuclei_layer = draw_nucleus(center_x, center_y, semi_major, semi_minor, intensity)
            placed_nuclei.append((center_x, center_y, max_radius))
            break

    # ================================================================
    # Composizione finale
    # ================================================================

    final_image = background + nuclei_layer
    final_image = np.clip(final_image, 0, 255).astype(np.uint8)
    img = Image.fromarray(final_image)

    if blur_radius > 0:
        img = img.filter(ImageFilter.GaussianBlur(radius=max(np.random.normal(blur_radius, blur_radius/15), 0)))

    if output_path:
        img.save(output_path)
        txt_path = output_path.rsplit('.', 1)[0] + '.txt'
        with open(txt_path, 'w') as f:
            f.write('\n'.join(annotations))

    return img, annotations


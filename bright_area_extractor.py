def process_folder(input_folder, output_folder, threshold=200, min_area=100):
    """
    Processa tutte le immagini in una cartella ed estrae le zone luminose.

    Args:
        input_folder: Cartella con le immagini da analizzare
        output_folder: Cartella dove salvare i ritagli
        threshold: Soglia di luminosità (0-255)
        min_area: Area minima in pixel
    """
    try:
        drive.mount('/content/drive')
    except:
        pass

    # Crea la cartella di output se non esiste
    os.makedirs(output_folder, exist_ok=True)

    # Estensioni supportate
    image_extensions = {'.jpg', '.jpeg', '.png', '.bmp', '.tiff', '.webp'}

    # Trova tutte le immagini nella cartella
    input_path = Path(input_folder)
    image_files = [f for f in input_path.iterdir()
                   if f.is_file() and f.suffix.lower() in image_extensions]

    if not image_files:
        print(f"⚠️ Nessuna immagine trovata in {input_folder}")
        return

    print("="*70)
    print("ESTRAZIONE ZONE LUMINOSE - BATCH")
    print("="*70)
    print(f"Cartella input: {input_folder}")
    print(f"Cartella output: {output_folder}")
    print(f"Immagini trovate: {len(image_files)}")
    print(f"Soglia luminosità: {threshold} (0-255)")
    print(f"Area minima: {min_area} pixel²")
    print("="*70)
    print()

    # Crea l'estrattore
    extractor = BrightAreaExtractor(threshold=threshold, min_area=min_area)

    # Statistiche
    total_areas = 0
    processed_images = 0

    # Processa ogni immagine
    for img_file in image_files:
        print(f"📷 Elaborazione: {img_file.name}")

        try:
            # Estrai le zone luminose
            bright_areas, rectangles_info = extractor.extract_bright_areas(str(img_file))

            if bright_areas:
                # Salva ogni zona ritagliata
                base_name = img_file.stem  # Nome senza estensione

                for i, area_img in enumerate(bright_areas, 1):
                    # Nome file: originale_zona1.jpg, originale_zona2.jpg, etc.
                    output_name = f"{base_name}_zona{i}.jpg"
                    output_path = os.path.join(output_folder, output_name)

                    # Salva l'immagine ritagliata
                    cv2.imwrite(output_path, area_img)

                print(f"   ✅ Salvate {len(bright_areas)} zone")
                total_areas += len(bright_areas)
                processed_images += 1

                # Mostra info dettagliate
                for i, info in enumerate(rectangles_info, 1):
                    print(f"      Zona {i}: {info['width']}×{info['height']}px, "
                          f"pos ({info['x']},{info['y']})")
            else:
                print(f"   ⚠️ Nessuna zona luminosa trovata")

        except Exception as e:
            print(f"   ❌ Errore: {str(e)}")

        print()

    # Riepilogo finale
    print("="*70)
    print("RIEPILOGO")
    print("="*70)
    print(f"Immagini processate: {processed_images}/{len(image_files)}")
    print(f"Zone luminose estratte: {total_areas}")
    print(f"Media zone per immagine: {total_areas/processed_images:.1f}" if processed_images > 0 else "N/A")
    print(f"File salvati in: {output_folder}")
    print("="*70)


import cv2
import numpy as np
from google.colab import drive
import matplotlib.pyplot as plt

class BrightAreaExtractor:
    def __init__(self, threshold=200, min_area=100):
        self.threshold = threshold
        self.min_area = min_area

    def extract_bright_areas(self, image_path):
        img = cv2.imread(image_path)
        if img is None:
            raise ValueError(f"Impossibile caricare l'immagine: {image_path}")

        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        _, bright_mask = cv2.threshold(gray, self.threshold, 255, cv2.THRESH_BINARY)
        contours, _ = cv2.findContours(bright_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        bright_areas = []
        rectangles_info = []

        for contour in contours:
            x, y, w, h = cv2.boundingRect(contour)
            area = w * h

            if area >= self.min_area:
                cropped = img[y:y+h, x:x+w].copy()
                bright_areas.append(cropped)
                rectangles_info.append({
                    'x': x, 'y': y, 'width': w, 'height': h, 'area': area
                })

        return bright_areas, rectangles_info

    def display_bright_areas(self, bright_areas, rectangles_info):
        if not bright_areas:
            print("⚠️ Nessuna zona luminosa rilevata con i parametri attuali.")
            print(f"   Soglia: {self.threshold}, Area minima: {self.min_area} pixel")
            return

        num_areas = len(bright_areas)
        print(f"✅ Trovate {num_areas} zone luminose\n")

        cols = min(3, num_areas)
        rows = (num_areas + cols - 1) // cols

        fig, axes = plt.subplots(rows, cols, figsize=(5*cols, 5*rows))

        if num_areas == 1:
            axes = np.array([axes])

        axes = axes.flatten() if num_areas > 1 else axes

        for i, (area_img, info) in enumerate(zip(bright_areas, rectangles_info)):
            area_rgb = cv2.cvtColor(area_img, cv2.COLOR_BGR2RGB)
            axes[i].imshow(area_rgb)
            axes[i].set_title(
                f"Zona {i+1}\n"
                f"Posizione: ({info['x']}, {info['y']})\n"
                f"Dimensioni: {info['width']}×{info['height']}px\n"
                f"Area: {info['area']} px²",
                fontsize=10
            )
            axes[i].axis('off')

            print(f"Zona {i+1}:")
            print(f"  • Posizione originale: ({info['x']}, {info['y']})")
            print(f"  • Dimensioni: {info['width']} × {info['height']} pixel")
            print(f"  • Area totale: {info['area']} pixel²\n")

        for i in range(num_areas, len(axes)):
            axes[i].axis('off')

        plt.tight_layout()
        plt.show()


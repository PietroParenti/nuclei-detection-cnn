def apply_nms(preds, iou_threshold):
    """NMS greedy: ordina per confidence, scarta box che si sovrappongono troppo a uno già tenuto."""
    preds_sorted = sorted(preds, key=lambda p: p['confidence'], reverse=True)
    kept = []
    for p in preds_sorted:
        if all(compute_iou(p['box'], k['box']) < iou_threshold for k in kept):
            kept.append(p)
    return kept


def find_best_nms_iou(images_folder, predictions_folder, gt_labels_folder,
                       iou_nms_range=np.arange(0.2, 0.85, 0.05),
                       fixed_conf=0.45,
                       iou_thresh_eval=0.5):
    dataset_raw = build_dataset_from_folders(
        images_folder=images_folder,
        predictions_folder=predictions_folder,
        gt_labels_folder=gt_labels_folder,
        min_conf=fixed_conf
    )

    results = []
    for iou_nms in iou_nms_range:
        dataset_nms = [
            {'preds': apply_nms(e['preds'], iou_nms), 'gts': e['gts'], 'name': e['name']}
            for e in dataset_raw
        ]
        precision, recall, f1, tp, fp, fn = compute_precision_recall_f1(dataset_nms, iou_thresh_eval)
        mae, bias = compute_count_error(dataset_nms)
        results.append({'iou_nms': round(iou_nms, 2), 'precision': precision, 'recall': recall,
                        'f1': f1, 'count_mae': mae, 'count_bias': bias})

    results.sort(key=lambda x: x['f1'], reverse=True)
    return results

def select_best_by_f1_then_mae(results, top_k=3):
    """Tra i top_k risultati con F1 più alto, sceglie quello con MAE di conteggio più basso."""
    top_candidates = sorted(results, key=lambda x: x['f1'], reverse=True)[:top_k]
    return min(top_candidates, key=lambda x: x['count_mae'])


def _get_or_create_worksheet():
    try:
        sh = gc.open(SHEET_NAME)
    except gspread.SpreadsheetNotFound:
        sh = gc.create(SHEET_NAME)
        print(f"📄 Creato nuovo Google Sheet: {SHEET_NAME}")

    try:
        ws = sh.worksheet(WORKSHEET_NAME)
    except gspread.WorksheetNotFound:
        ws = sh.add_worksheet(title=WORKSHEET_NAME, rows=100, cols=20)

    return sh, ws


def save_metrics_to_gsheet(model_name, f1, precision, recall, map50, map75, map_small,
                            mae, bias, extra_info=None):
    """
    Salva (o aggiorna) i risultati di un modello in un Google Sheet cumulativo.
    Se model_name esiste già, sostituisce quella riga invece di duplicarla.
    """
    row = {
        'modello': model_name,
        'F1': round(f1, 4),
        'Precision': round(precision, 4),
        'Recall': round(recall, 4),
        'mAP50': round(map50, 4),
        'mAP75': round(map75, 4),
        'mAP_small': round(map_small, 4),
        'MAE_conteggio': round(mae, 2),
        'Bias_conteggio': round(bias, 2),
    }
    if extra_info:
        row.update(extra_info)

    sh, ws = _get_or_create_worksheet()

    existing_df = get_as_dataframe(ws, evaluate_formulas=True, header=0).dropna(how='all')
    new_row_df = pd.DataFrame([row])

    if not existing_df.empty and 'modello' in existing_df.columns:
        existing_df = existing_df[existing_df['modello'] != model_name]
        updated_df = pd.concat([existing_df, new_row_df], ignore_index=True)
    else:
        updated_df = new_row_df

    ws.clear()
    set_with_dataframe(ws, updated_df)

    print(f"✅ Risultati salvati nel Google Sheet: {SHEET_NAME} (foglio: {WORKSHEET_NAME})")
    print(f"🔗 {sh.url}")

    return updated_df


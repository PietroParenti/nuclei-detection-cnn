def load_gt_from_yolo_label(label_path, img_w, img_h):
    """Carica ground truth da file .txt in formato YOLO normalizzato."""
    gts = []
    with open(label_path, 'r') as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) < 5:
                continue
            _, cx, cy, w, h = map(float, parts[:5])
            x1 = (cx - w/2) * img_w
            y1 = (cy - h/2) * img_h
            x2 = (cx + w/2) * img_w
            y2 = (cy + h/2) * img_h
            gts.append({'box': (x1, y1, x2, y2)})
    return gts



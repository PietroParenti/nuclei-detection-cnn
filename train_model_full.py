def grid_search_conf_iou(dataset_full,
                          conf_range=np.arange(0.05, 0.95, 0.05),
                          iou_nms_range=np.arange(0.20, 0.95, 0.05),
                          iou_thresh_eval=0.5):
    """
    Grid search congiunta su conf e IoU-NMS, partendo da un dataset già caricato
    (tutte le predizioni salvate, es. min_conf=0.05, nessun NMS applicato).
    """
    results = []
    for conf_thresh in conf_range:
        dataset_conf = [
            {'preds': [p for p in e['preds'] if p['confidence'] >= conf_thresh],
             'gts': e['gts'], 'name': e['name']}
            for e in dataset_full
        ]
        for iou_nms in iou_nms_range:
            dataset_final = [
                {'preds': apply_nms(e['preds'], iou_nms), 'gts': e['gts'], 'name': e['name']}
                for e in dataset_conf
            ]
            precision, recall, f1, tp, fp, fn = compute_precision_recall_f1(dataset_final, iou_thresh_eval)
            mae, bias = compute_count_error(dataset_final)
            results.append({
                'conf': round(conf_thresh, 2),
                'iou_nms': round(iou_nms, 2),
                'precision': precision, 'recall': recall, 'f1': f1,
                'tp': tp, 'fp': fp, 'fn': fn,
                'count_mae': mae, 'count_bias': bias,
            })
    results.sort(key=lambda x: x['f1'], reverse=True)
    return results


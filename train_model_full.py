def save_predictions(preds, img_w, img_h, output_path):
    """
    Salva le predizioni in formato YOLO esteso (con confidence).
    preds: lista di dict {'box': (x1,y1,x2,y2), 'confidence': float, 'class_id': int (opzionale)}
    """
    lines = []
    for p in preds:
        x1, y1, x2, y2 = p['box']
        cls = p.get('class_id', 0)
        cx = (x1 + x2) / 2 / img_w
        cy = (y1 + y2) / 2 / img_h
        w  = (x2 - x1) / img_w
        h  = (y2 - y1) / img_h
        lines.append(f"{cls} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f} {p['confidence']:.6f}")

    with open(output_path, 'w') as f:
        f.write('\n'.join(lines))

def find_images(folder):
    """Trova tutte le immagini in una cartella, gestendo estensioni sia minuscole che maiuscole."""
    exts = ["jpg", "jpeg", "png", "bmp", "tiff", "webp"]
    files = []
    for ext in exts:
        files += list(Path(folder).glob(f"*.{ext}"))
        files += list(Path(folder).glob(f"*.{ext.upper()}"))
    return sorted(set(files))


# 1. Modifica run_and_save_predictions per accettare anche 'iou' (permissivo)
def run_and_save_predictions(model, images_folder, output_folder, conf=0.05, iou=0.99, imgsz=1024, max_det=2000):
    os.makedirs(output_folder, exist_ok=True)
    image_files = find_images(images_folder)

    for img_path in image_files:
        img = cv2.imread(str(img_path))
        img_h, img_w = img.shape[:2]

        results = model(img, conf=conf, iou=iou, imgsz=imgsz, max_det=max_det, end2end=False, verbose=False)[0]

        preds = []
        for box in results.boxes:
            x1, y1, x2, y2 = box.xyxy[0].tolist()
            preds.append({
                'box': (x1, y1, x2, y2),
                'confidence': float(box.conf[0]),
                'class_id': int(box.cls[0])
            })

        out_path = Path(output_folder) / f"{img_path.stem}.txt"
        save_predictions(preds, img_w, img_h, out_path)

    print(f"✅ Predizioni salvate (NMS quasi disattivato, iou={iou}) in: {output_folder}")


def load_predictions_from_yolo_format(pred_path, img_w, img_h, min_conf=0.0):
    """Carica predizioni salvate con save_predictions(), filtrando opzionalmente per confidence minima."""
    preds = []
    if not os.path.exists(pred_path):
        return preds
    with open(pred_path, 'r') as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) < 6:
                continue
            cls, cx, cy, w, h, conf = parts[0], *map(float, parts[1:6])
            if conf < min_conf:
                continue
            x1 = (cx - w/2) * img_w
            y1 = (cy - h/2) * img_h
            x2 = (cx + w/2) * img_w
            y2 = (cy + h/2) * img_h
            preds.append({'box': (x1, y1, x2, y2), 'confidence': conf, 'class_id': int(cls)})
    return preds


def build_dataset_from_folders(images_folder, predictions_folder, gt_labels_folder, min_conf=0.0):
    """
    Costruisce il 'dataset' pronto per benchmark_detection(), leggendo tutto da disco
    — nessuna chiamata al modello.
    """
    image_files = find_images(images_folder)
    dataset = []

    for img_path in image_files:
        img = cv2.imread(str(img_path))
        img_h, img_w = img.shape[:2]

        pred_path = Path(predictions_folder) / f"{img_path.stem}.txt"
        gt_path   = Path(gt_labels_folder) / f"{img_path.stem}.txt"

        preds = load_predictions_from_yolo_format(pred_path, img_w, img_h, min_conf=min_conf)
        gts   = load_gt_from_yolo_label(gt_path, img_w, img_h) if gt_path.exists() else []

        dataset.append({'preds': preds, 'gts': gts, 'name': img_path.name})

    return dataset


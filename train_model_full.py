def compute_iou(box_a, box_b):
    """IoU tra due box in formato (x1, y1, x2, y2)."""
    ix1 = max(box_a[0], box_b[0])
    iy1 = max(box_a[1], box_b[1])
    ix2 = min(box_a[2], box_b[2])
    iy2 = min(box_a[3], box_b[3])

    inter_w = max(0, ix2 - ix1)
    inter_h = max(0, iy2 - iy1)
    inter = inter_w * inter_h

    if inter == 0:
        return 0.0

    area_a = (box_a[2] - box_a[0]) * (box_a[3] - box_a[1])
    area_b = (box_b[2] - box_b[0]) * (box_b[3] - box_b[1])

    return inter / (area_a + area_b - inter + 1e-9)


def box_area(box):
    return (box[2] - box[0]) * (box[3] - box[1])


def match_predictions_to_gt(preds, gts, iou_threshold):
    """
    Matching greedy (stile COCO): predizioni ordinate per confidence decrescente,
    ognuna si prende il miglior GT libero disponibile sopra soglia IoU.
    """
    gt_matched = [False] * len(gts)
    preds_sorted = sorted(preds, key=lambda p: p['confidence'], reverse=True)
    results = []

    for pred in preds_sorted:
        best_iou, best_idx = 0.0, -1
        for i, gt in enumerate(gts):
            if gt_matched[i]:
                continue
            iou = compute_iou(pred['box'], gt['box'])
            if iou > best_iou:
                best_iou, best_idx = iou, i

        if best_iou >= iou_threshold:
            gt_matched[best_idx] = True
            results.append((pred['confidence'], 1))   # TP
        else:
            results.append((pred['confidence'], 0))   # FP

    return results, sum(gt_matched)


def compute_ap_dataset(dataset, iou_threshold, area_range=None):
    """AP 'pooled' su tutto il dataset (protocollo COCO), interpolazione a 101 punti."""
    all_results = []
    total_gt = 0

    for entry in dataset:
        preds = entry['preds']
        gts = entry['gts']

        if area_range is not None:
            min_a, max_a = area_range
            preds = [p for p in preds if min_a <= box_area(p['box']) < max_a]
            gts   = [g for g in gts   if min_a <= box_area(g['box']) < max_a]

        total_gt += len(gts)

        if len(preds) == 0:
            continue

        results, _ = match_predictions_to_gt(preds, gts, iou_threshold)
        all_results.extend(results)

    if total_gt == 0 or len(all_results) == 0:
        return 0.0

    all_results.sort(key=lambda x: x[0], reverse=True)
    tps = np.array([r[1] for r in all_results])
    fps = 1 - tps

    tp_cum = np.cumsum(tps)
    fp_cum = np.cumsum(fps)

    recall_curve    = tp_cum / (total_gt + 1e-9)
    precision_curve = tp_cum / (tp_cum + fp_cum + 1e-9)

    ap = 0.0
    for t in np.linspace(0, 1, 101):
        prec_at_t = precision_curve[recall_curve >= t]
        ap += (np.max(prec_at_t) if len(prec_at_t) > 0 else 0.0)
    ap /= 101

    return ap


def compute_precision_recall_f1(dataset, iou_threshold=0.5, area_range=None):
    """
    Precision/Recall/F1 a soglia di confidence fissa — le 'preds' vanno
    già filtrate alla soglia operativa PRIMA di chiamare questa funzione.
    """
    total_tp, total_fp, total_fn = 0, 0, 0

    for entry in dataset:
        preds = entry['preds']
        gts   = entry['gts']

        if area_range is not None:
            min_a, max_a = area_range
            preds = [p for p in preds if min_a <= box_area(p['box']) < max_a]
            gts   = [g for g in gts   if min_a <= box_area(g['box']) < max_a]

        if len(preds) == 0:
            total_fn += len(gts)
            continue

        results, n_matched_gt = match_predictions_to_gt(preds, gts, iou_threshold)
        tp = sum(r[1] for r in results)
        fp = len(results) - tp
        fn = len(gts) - n_matched_gt

        total_tp += tp
        total_fp += fp
        total_fn += fn

    precision = total_tp / (total_tp + total_fp + 1e-9)
    recall    = total_tp / (total_tp + total_fn + 1e-9)
    f1        = 2 * precision * recall / (precision + recall + 1e-9)

    return precision, recall, f1, total_tp, total_fp, total_fn


def compute_count_error(dataset):
    """MAE e bias medio sull'errore di conteggio (predette - GT)."""
    diffs = np.array([len(e['preds']) - len(e['gts']) for e in dataset])
    return float(np.mean(np.abs(diffs))), float(np.mean(diffs))


SMALL_AREA_THRESH = 1024  # 32x32 px, soglia COCO per "small"

def benchmark_detection(dataset, iou_thresh_pr=0.5, small_area_thresh=SMALL_AREA_THRESH):
    """
    dataset: lista di immagini, ciascuna:
        {'preds': [{'box':(x1,y1,x2,y2), 'confidence':float}, ...],
         'gts':   [{'box':(x1,y1,x2,y2)}, ...]}
    """
    metrics = {}

    precision, recall, f1, tp, fp, fn = compute_precision_recall_f1(dataset, iou_thresh_pr)
    metrics.update(precision=precision, recall=recall, f1=f1, tp=tp, fp=fp, fn=fn)

    metrics['map50'] = compute_ap_dataset(dataset, iou_threshold=0.5)
    metrics['map75'] = compute_ap_dataset(dataset, iou_threshold=0.75)

    ap_list_small = [
        compute_ap_dataset(dataset, iou_threshold=round(t, 2), area_range=(0, small_area_thresh))
        for t in np.arange(0.5, 1.0, 0.05)
    ]
    metrics['map_small'] = float(np.mean(ap_list_small))

    mae, bias = compute_count_error(dataset)
    metrics['count_mae'] = mae
    metrics['count_bias'] = bias

    metrics['n_images']      = len(dataset)
    metrics['n_gt_total']    = sum(len(e['gts']) for e in dataset)
    metrics['n_pred_total']  = sum(len(e['preds']) for e in dataset)

    return metrics


